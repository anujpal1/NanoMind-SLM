"""Run one bounded, revision-pinned audit of the training dataset."""

from collections import Counter
from itertools import islice
from math import isfinite
from pathlib import Path
from statistics import mean
from typing import Any

import yaml
from datasets import IterableDataset, load_dataset

from nanomind_slm.data.filtering import (
    evaluate_common_requirements,
    evaluate_quality_requirements,
)

CONFIG_PATH = Path("configs/data.yaml")


def parse_size(value: Any) -> int | None:
    """Convert a finite, non-negative dataset size to an integer."""
    if value is None or isinstance(value, bool):
        return None

    try:
        numeric_value = float(value)
    except (TypeError, ValueError):
        return None

    if not isfinite(numeric_value) or numeric_value < 0:
        return None

    return int(numeric_value)


def load_config() -> dict[str, Any]:
    """Load the dataset configuration."""
    with CONFIG_PATH.open(encoding="utf-8") as file:
        config = yaml.safe_load(file)

    if not isinstance(config, dict):
        raise TypeError("Dataset configuration must be a dictionary")

    return config


def print_filter_results(
    name: str,
    counts: Counter[str],
    total: int,
) -> None:
    """Print acceptance and rejection counts for one filter."""
    accepted = counts["accepted"]
    rejected = total - accepted
    acceptance_rate = accepted / total * 100 if total else 0.0

    print(f"\n{name}")
    print(f"  accepted: {accepted}")
    print(f"  rejected: {rejected}")
    print(f"  acceptance rate: {acceptance_rate:.2f}%")
    print("  decision reasons:")

    for reason, count in counts.most_common():
        print(f"    {reason}: {count}")


def main() -> None:
    """Inspect metadata and compare filters without storing source files."""
    config = load_config()
    dataset_config = config["dataset"]
    audit_config = config["audit"]
    filter_config = config["filtering"]

    dataset_id = str(dataset_config["id"])
    revision = str(dataset_config["revision"]).strip()
    split = str(dataset_config["split"])
    streaming = dataset_config["streaming"]
    sample_limit = int(audit_config["sample_limit"])
    expected_fields = {str(field) for field in config["required_fields"]}
    allowed_licenses = {str(item) for item in config["license_policy"]["allow"]}

    if not revision:
        raise ValueError("A pinned dataset revision is required")

    if streaming is not True:
        raise ValueError("Dataset streaming must remain enabled")

    if not 1 <= sample_limit <= 1000:
        raise ValueError("Audit sample_limit must be between 1 and 1000")

    print(f"Dataset: {dataset_id}")
    print(f"Revision: {revision}")
    print(f"Split: {split}")
    print(f"Maximum records: {sample_limit}")
    print("Streaming: enabled")
    print("Source-code printing and storage: disabled")

    dataset = load_dataset(
        dataset_id,
        split=split,
        revision=revision,
        streaming=streaming,
    )

    if not isinstance(dataset, IterableDataset):
        raise TypeError("Expected a streaming IterableDataset")

    missing_field_counts: Counter[str] = Counter()
    license_counts: Counter[str] = Counter()
    baseline_counts: Counter[str] = Counter()
    quality_counts: Counter[str] = Counter()
    file_sizes: list[int] = []
    autogenerated_count = 0
    missing_content_count = 0
    observed_count = 0

    for record in islice(dataset, sample_limit):
        observed_count += 1
        license_counts[str(record.get("license") or "unknown")] += 1

        for field in expected_fields:
            if field not in record:
                missing_field_counts[field] += 1

        size = parse_size(record.get("size"))
        if size is not None:
            file_sizes.append(size)

        if record.get("autogenerated") is True:
            autogenerated_count += 1

        content = record.get("content")
        if not isinstance(content, str) or not content.strip():
            missing_content_count += 1

        baseline_decision = evaluate_common_requirements(
            record,
            allowed_licenses,
        )
        quality_decision = evaluate_quality_requirements(
            record,
            allowed_licenses,
            min_characters=int(filter_config["min_characters"]),
            max_characters=int(filter_config["max_characters"]),
            max_line_length=int(filter_config["max_line_length"]),
            allow_autogenerated=bool(filter_config["allow_autogenerated"]),
        )
        baseline_counts[baseline_decision.reason] += 1
        quality_counts[quality_decision.reason] += 1

    print("\nMetadata summary")
    print(f"  records inspected: {observed_count}")
    print(f"  records with numeric size: {len(file_sizes)}")
    print(f"  autogenerated records: {autogenerated_count}")
    print(f"  missing or empty content: {missing_content_count}")
    print(f"  missing required fields: {dict(sorted(missing_field_counts.items()))}")

    if file_sizes:
        print(f"  minimum declared size: {min(file_sizes):,}")
        print(f"  maximum declared size: {max(file_sizes):,}")
        print(f"  average declared size: {mean(file_sizes):,.2f}")

    print("\nLicense counts")
    for license_name, count in license_counts.most_common():
        print(f"  {license_name}: {count}")

    print_filter_results("Baseline filter", baseline_counts, observed_count)
    print_filter_results("Quality filter", quality_counts, observed_count)

    if observed_count != sample_limit:
        raise RuntimeError(
            f"Expected {sample_limit} records, received {observed_count}"
        )

    if missing_field_counts:
        raise RuntimeError(
            f"Required dataset fields are missing: {dict(missing_field_counts)}"
        )

    if not file_sizes:
        raise RuntimeError("No valid file sizes were found")

    if quality_counts["accepted"] > baseline_counts["accepted"]:
        raise RuntimeError("Quality filter accepted more records than the baseline")

    print("\nRevision-pinned dataset audit: PASSED")


if __name__ == "__main__":
    main()
